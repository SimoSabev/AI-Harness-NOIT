#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES.md from the same pnpm output as check-licenses (D-052, D-077).
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { pnpmLicenses } from "./check-licenses.mjs";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * @param {Record<string, {name: string, versions: string[], license: string, homepage?: string, author?: string}[]>} all
 * @param {Record<string, {name: string, versions: string[]}[]>} prod
 */
export function renderThirdParty(all, prod) {
  const prodIds = new Set(Object.values(prod).flatMap((ps) => ps.flatMap((p) => p.versions.map((v) => `${p.name}@${v}`))));
  const rows = Object.values(all)
    .flat()
    .filter((p) => !p.name.startsWith("@mandat/"))
    .flatMap((p) => p.versions.map((v) => ({ ...p, version: v, id: `${p.name}@${v}` })))
    .sort((a, b) => a.id.localeCompare(b.id));
  const lines = [
    "# Third-party licenses",
    "",
    "Generated by `pnpm licenses:third-party` from `pnpm licenses list --json --recursive` (and `--prod`). Do not edit by hand.",
    "",
    "Claude Code (`@anthropic-ai/claude-code`, proprietary, Anthropic Commercial Terms) is NOT a dependency: it runs as a",
    "separate process inside the locally built `mandat-sandbox` image and is never distributed (4.1, 4.3).",
    "",
    `Packages: ${rows.length} (runtime: ${rows.filter((r) => prodIds.has(r.id)).length}).`,
    "",
    "| Package | Version | License | Scope | Homepage |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${prodIds.has(r.id) ? "runtime" : "dev"} | ${r.homepage ?? ""} |`),
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(repo, "THIRD_PARTY_LICENSES.md"), renderThirdParty(pnpmLicenses(false), pnpmLicenses(true)));
  console.log("wrote THIRD_PARTY_LICENSES.md");
}
