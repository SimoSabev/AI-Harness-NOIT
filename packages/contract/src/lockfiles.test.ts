import { describe, expect, it } from "vitest";
import { INSTALL_ARGV, LOCKFILE, installCommand, lockAllowlist, pnpmAllowlist, yarnAllowlist } from "./lockfiles.js";

const PNPM = `lockfileVersion: '9.0'

importers:

  .:
    devDependencies:
      vitest:
        specifier: 5.0.5
        version: 5.0.5

packages:

  '@vitest/expect@5.0.5':
    resolution: {integrity: sha512-AAAA}

  vitest@5.0.5:
    resolution: {integrity: sha512-BBBB}
    hasBin: true

snapshots:

  vitest@5.0.5: {}
`;

const YARN = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@vitest/expect@5.0.5":
  version "5.0.5"
  resolved "https://registry.yarnpkg.com/@vitest/expect/-/expect-5.0.5.tgz#0123abcd"
  integrity sha512-AAAA

vitest@^5.0.0, vitest@5.0.5:
  version "5.0.5"
  resolved "https://registry.npmjs.org/vitest/-/vitest-5.0.5.tgz"
  integrity sha512-BBBB
`;

const paths = (r: ReturnType<typeof lockAllowlist>) => (r.ok ? r.routes.map((x) => x.match.path) : r.reason);

describe("lockfiles (D-301)", () => {
  it("имена и команди за инсталиране", () => {
    expect(LOCKFILE).toEqual({ npm: "package-lock.json", pnpm: "pnpm-lock.yaml", yarn: "yarn.lock" });
    expect(INSTALL_ARGV.pnpm.slice(0, 4)).toEqual(["pnpm", "install", "--frozen-lockfile", "--ignore-scripts"]);
    expect(INSTALL_ARGV.pnpm).toContain("--registry=http://egress-gate/npm/");
    expect(INSTALL_ARGV.yarn).toEqual(["yarn", "install", "--frozen-lockfile", "--ignore-scripts", "--non-interactive"]);
    expect(installCommand("npm")).toEqual(["npm", "ci", "--ignore-scripts", "--no-audit", "--no-fund"]);
    const y = installCommand("yarn");
    expect(y.slice(0, 2)).toEqual(["/bin/sh", "-c"]);
    expect(y[2]).toContain("http://egress-gate/npm/");
    expect(y[2]).toMatch(/yarn install --frozen-lockfile --ignore-scripts --non-interactive; rc=\$\?; cp \/tmp\/yarn.lock.orig yarn.lock; exit \$rc$/);
  });

  it("pnpm v9: tarball и packument пътища през /npm/, scoped в трите изписвания", () => {
    const r = pnpmAllowlist(PNPM);
    expect(r.ok && r.packages).toBe(2);
    expect(paths(r)).toEqual([
      "/npm/@vitest/expect/-/expect-5.0.5.tgz", "/npm/@vitest/expect", "/npm/@vitest%2fexpect", "/npm/@vitest%2Fexpect",
      "/npm/vitest/-/vitest-5.0.5.tgz", "/npm/vitest",
    ]);
  });

  it("pnpm: tarball/git зависимост, workspace, стара версия, без integrity → отказ", () => {
    expect(paths(pnpmAllowlist(PNPM.replace("resolution: {integrity: sha512-BBBB}", "resolution: {tarball: https://x.example/v.tgz}")))).toBe("git_or_url_dep");
    expect(paths(pnpmAllowlist(PNPM.replace("importers:\n\n  .:", "importers:\n\n  packages/a:\n    {}\n  .:")))).toBe("workspace");
    expect(paths(pnpmAllowlist(PNPM.replace("'9.0'", "'6.0'")))).toBe("not_v3");
    expect(paths(pnpmAllowlist(PNPM.replace("{integrity: sha512-AAAA}", "{integrity: sha1-AAAA}")))).toBe("bad_integrity");
    expect(paths(pnpmAllowlist("::: not yaml"))).toBe("not_v3");
  });

  it("yarn v1: resolved от npm/yarnpkg → /npm/…, без #hash", () => {
    const r = yarnAllowlist(YARN);
    expect(r.ok && r.packages).toBe(2);
    expect(paths(r)).toEqual([
      "/npm/@vitest/expect/-/expect-5.0.5.tgz", "/npm/@vitest/expect", "/npm/@vitest%2fexpect", "/npm/@vitest%2Fexpect",
      "/npm/vitest/-/vitest-5.0.5.tgz", "/npm/vitest",
    ]);
  });

  it("yarn: berry, чужд хост, без integrity → отказ", () => {
    expect(paths(yarnAllowlist('__metadata:\n  version: 8\n\n"vitest@npm:5.0.5":\n  version: 5.0.5\n'))).toBe("yarn_berry");
    expect(paths(yarnAllowlist(YARN.replace("https://registry.npmjs.org/vitest", "https://evil.example/vitest")))).toBe("foreign_resolved");
    expect(paths(yarnAllowlist(YARN.replace("  integrity sha512-BBBB\n", "")))).toBe("bad_integrity");
    expect(paths(yarnAllowlist(YARN.replace('resolved "https://registry.npmjs.org/vitest/-/vitest-5.0.5.tgz"', 'resolved "git+https://github.com/x/y.git#abc"')))).toBe("git_or_url_dep");
  });

  it("lockAllowlist по мениджър; липсващ lockfile → missing", () => {
    expect(lockAllowlist("pnpm", PNPM).ok).toBe(true);
    expect(lockAllowlist("yarn", YARN).ok).toBe(true);
    expect(paths(lockAllowlist("pnpm", null))).toBe("missing_lockfile");
    expect(lockAllowlist("npm", JSON.stringify({ lockfileVersion: 3, packages: { "": {} } })).ok).toBe(true);
  });
});
