import { describe, expect, it } from "vitest";
import { FIXTURES, memView } from "./fixtures.test-helper.js";
import { BEGIN, END, MAX_LINES, applyManagedBlock, claudeMd, generateHarnessFiles, renderAgentsBlock } from "./agents-md.js";
import { findInvisible } from "./invisible.js";
import { propose } from "./propose.js";
import { scanRepo } from "./scan.js";

const scan = scanRepo(memView(FIXTURES["npm-vitest"] as Record<string, string>));
const p = propose(scan);
const input = { policy: p.policy, scripts: scan.scripts, packageManager: "npm", configSha256: p.sha256, version: 1, links: ["README.md"] };

describe("agents-md (т. 8.2 (8))", () => {
  it("≤ 60 реда; команди, граници, типове; футър", () => {
    const b = renderAgentsBlock(input);
    expect(b.split("\n").length).toBeLessThanOrEqual(MAX_LINES);
    expect(b).toContain("- install: `npm ci --ignore-scripts`");
    expect(b).toContain("- test: `npm run test`");
    expect(b).toContain("Mandat runs the tests. Do not report a test result yourself.");
    expect(b).toContain("- bugfix: `src/**` (tests may not change)");
    expect(b).toContain(`Generated by Mandat from .mandat.yml@sha256:${p.sha256.slice(7, 15)} v1. Do not edit; run mandat harness diff`);
    expect(b).toContain("[README.md](README.md)");
  });
  it("без права, hooks, MCP, allowed-tools, тайни; без невидими знаци (и при одобрено резюме с U+202E)", () => {
    const b = renderAgentsBlock({ ...input, summary: "Магазин \u202Eдемо" });
    // `.mcp.json` may appear only as a protected path, never as configuration
    for (const w of [/hooks?/i, /mcpServers|mcp add|mcp server/i, /allowed.?tools/i, /permission/i, /api[_-]?key/i, /secret/i, /token/i]) expect(b).not.toMatch(w);
    expect(findInvisible(b)).toEqual([]);
  });
  it("managed block запазва чуждия текст байт по байт", () => {
    const mine = "# Our notes\r\n\nKeep this é exact.\n";
    const once = applyManagedBlock(mine, `${BEGIN}\nA\n${END}`);
    expect(once.startsWith(mine)).toBe(true);
    const twice = applyManagedBlock(`${once}tail text`, `${BEGIN}\nB\n${END}`);
    expect(twice).toBe(`${mine}\n${BEGIN}\nB\n${END}\ntail text`);
    expect(applyManagedBlock(null, "X")).toBe("X\n");
  });
  it("генерираните файлове са винаги в protected_paths и config_paths (D3 → UNKNOWN)", () => {
    for (const f of [".mandat.yml", "AGENTS.md", "CLAUDE.md"]) {
      expect(p.policy.protected_paths).toContain(f);
      expect(p.policy.config_paths).toContain(f);
    }
  });
  it("CLAUDE.md = @AGENTS.md + 1 ред; трите файла с хеш", () => {
    expect(claudeMd(null)).toBe(`${BEGIN}\n@AGENTS.md\nMandat checks every change; the instructions are in AGENTS.md.\n${END}\n`);
    const g = generateHarnessFiles({ ...input, existingAgents: null, existingClaude: "mine\n", yaml: p.yaml });
    expect(g.map((f) => f.path)).toEqual([".mandat.yml", "AGENTS.md", "CLAUDE.md"]);
    expect(g[2]?.content.startsWith("mine\n")).toBe(true);
    for (const f of g) expect(f.sha256).toMatch(/^sha256:[0-9a-f]{64}$/);
  });
});
