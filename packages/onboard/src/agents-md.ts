import { sha256Tag } from "@mandat/contract";
import type { MandatPolicy } from "@mandat/contract";
import { stripInvisible } from "./invisible.js";

// Демо промпт т. 8.2 (8): AGENTS.md ≤ 60 lines from the approved policy by template (no LLM). Never permissions,
// hooks, MCP servers, allowed-tools or secrets (Ф5). An existing file keeps its text; only the managed block changes.
export const BEGIN = "<!-- mandat:begin -->";
export const END = "<!-- mandat:end -->";
export const MAX_LINES = 60;

export interface AgentsMdInput {
  policy: MandatPolicy;
  scripts: Record<string, string>;
  packageManager: string;
  configSha256: string; // "sha256:<hex>"
  version: number;
  summary?: string | null; // only an approved summary
  links?: string[]; // README.md, CONTRIBUTING.md (links, not copies)
}

const run = (pm: string, script: string) => (pm === "npm" ? `npm run ${script}` : `${pm} ${script}`);

export function renderAgentsBlock(i: AgentsMdInput): string {
  const p = i.policy;
  const cmd: string[] = [];
  cmd.push(`- install: \`${p.runtime.install}\``);
  if (i.scripts.test) cmd.push(`- test: \`${run(i.packageManager, "test")}\``);
  cmd.push(`- one test: \`${p.tests.framework === "jest" ? "npx jest -t \"<name>\"" : "npx vitest run -t \"<name>\""}\``);
  for (const s of ["lint", "typecheck", "dev"]) if (i.scripts[s]) cmd.push(`- ${s}: \`${run(i.packageManager, s)}\``);
  const tt = Object.entries(p.task_types).map(([name, t]) => `- ${name}: ${(t?.allowed_paths ?? []).map((g) => `\`${g}\``).join(", ")}${t?.may_change_tests ? " (tests may change)" : " (tests may not change)"}`);
  const lines = [
    BEGIN,
    "# Agent instructions",
    ...(i.summary ? ["", stripInvisible(i.summary).split("\n")[0]?.slice(0, 200) ?? ""] : []),
    "",
    "## Commands",
    ...cmd,
    "",
    "## Boundaries",
    `- Do not touch: ${p.protected_paths.slice(0, 12).map((g) => `\`${g}\``).join(", ")}`,
    "- Mandat runs the tests. Do not report a test result yourself.",
    "- Do not change `.mandat.yml`, `AGENTS.md`, `CLAUDE.md`.",
    "",
    "## Task types",
    ...tt,
    ...((i.links ?? []).length > 0 ? ["", "## More", ...(i.links ?? []).map((l) => `- [${l}](${l})`)] : []),
    "",
    `Generated by Mandat from .mandat.yml@sha256:${i.configSha256.replace(/^sha256:/, "").slice(0, 8)} v${i.version}. Do not edit; run mandat harness diff`,
    END,
  ];
  if (lines.length > MAX_LINES) throw new Error(`AGENTS.md block has ${lines.length} lines (max ${MAX_LINES})`);
  return stripInvisible(lines.join("\n"));
}

/** A new file = the block; an existing file keeps every other byte and gets the block replaced or appended. */
export function applyManagedBlock(existing: string | null, block: string): string {
  if (existing === null) return `${block}\n`;
  const b = existing.indexOf(BEGIN);
  const e = existing.indexOf(END);
  if (b >= 0 && e > b) return existing.slice(0, b) + block + existing.slice(e + END.length);
  const sep = existing.length === 0 || existing.endsWith("\n") ? "" : "\n";
  return `${existing}${sep}\n${block}\n`;
}

export function claudeMd(existing: string | null): string {
  return applyManagedBlock(existing, `${BEGIN}\n@AGENTS.md\nMandat checks every change; the instructions are in AGENTS.md.\n${END}`);
}

export interface Generated { path: string; content: string; sha256: string }
export function generateHarnessFiles(i: AgentsMdInput & { existingAgents: string | null; existingClaude: string | null; yaml: string }): Generated[] {
  const out = [
    { path: ".mandat.yml", content: i.yaml },
    { path: "AGENTS.md", content: applyManagedBlock(i.existingAgents, renderAgentsBlock(i)) },
    { path: "CLAUDE.md", content: claudeMd(i.existingClaude) },
  ];
  return out.map((f) => ({ ...f, sha256: sha256Tag(f.content) }));
}
